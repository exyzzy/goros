// Command msggen generates Go message types from ROS 2 .msg and .srv
// interface definitions.
//
//	msggen -in interfaces -out msgs -module bitbucket.org/goros/msgs
//
// Input layout mirrors ROS packages: <in>/<pkg>/msg/Foo.msg and
// <in>/<pkg>/srv/Bar.srv. Output is one Go package per ROS package.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	in := flag.String("in", "interfaces", "directory of <pkg>/msg/*.msg and <pkg>/srv/*.srv")
	out := flag.String("out", "msgs", "output directory (one Go package per ROS package)")
	module := flag.String("module", "bitbucket.org/goros/msgs", "import path of the output directory")
	flag.Parse()

	pkgs, err := loadPackages(*in)
	if err != nil {
		fail(err)
	}
	for _, p := range pkgs {
		if err := p.generate(*out, *module); err != nil {
			fail(fmt.Errorf("%s: %w", p.name, err))
		}
	}
	if err := generateAll(pkgs, *out, *module); err != nil {
		fail(err)
	}
}

// generateAll writes <out>/all/all.go, which blank-imports every generated
// package so tools can register all message types at once.
func generateAll(pkgs []*pkg, out, module string) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by msggen. DO NOT EDIT.\n\n")
	b.WriteString("// Package all registers every generated interface package with the\n// msg registry. Import it for side effects in tools that need to decode\n// arbitrary types by name (the goros CLI, bridges, recorders).\npackage all\n\nimport (\n")
	for _, p := range pkgs {
		fmt.Fprintf(&b, "\t_ %q\n", module+"/"+p.name)
	}
	b.WriteString(")\n")
	dir := filepath.Join(out, "all")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "all.go"), b.Bytes(), 0o644)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "msggen:", err)
	os.Exit(1)
}

// --- model -----------------------------------------------------------------

type fieldType struct {
	base    string // primitive name or "pkg/Name"
	pkg     string // package of nested type, "" for primitives
	name    string // Go-side type name of nested type
	isArray bool   // fixed-size array
	isSeq   bool   // sequence (bounded or unbounded)
	size    int    // array size or sequence bound (0 = unbounded)
	strMax  int    // bounded string length (0 = unbounded)
}

type field struct {
	name     string
	typ      fieldType
	def      string // default literal (raw text) or ""
	constant bool
	value    string
}

type message struct {
	pkg    *pkg
	name   string // Go type name, e.g. "String" or "AddTwoInts_Request"
	ros    string // "std_msgs/msg/String"
	fields []field
	consts []field
}

type service struct {
	name     string
	ros      string
	req, res *message
}

type pkg struct {
	name     string
	msgs     []*message
	srvs     []*service
	deps     map[string]bool
	srcFiles map[string]string
}

var primitives = map[string]string{
	"bool": "bool", "byte": "uint8", "char": "uint8",
	"int8": "int8", "uint8": "uint8", "int16": "int16", "uint16": "uint16",
	"int32": "int32", "uint32": "uint32", "int64": "int64", "uint64": "uint64",
	"float32": "float32", "float64": "float64",
	"string": "string", "wstring": "string",
}

func loadPackages(root string) ([]*pkg, error) {
	entries, err := os.ReadDir(root)
	if err != nil {
		return nil, err
	}
	var pkgs []*pkg
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		p := &pkg{name: e.Name(), deps: map[string]bool{}, srcFiles: map[string]string{}}
		msgDir := filepath.Join(root, e.Name(), "msg")
		files, _ := filepath.Glob(filepath.Join(msgDir, "*.msg"))
		sort.Strings(files)
		for _, f := range files {
			name := strings.TrimSuffix(filepath.Base(f), ".msg")
			src, err := os.ReadFile(f)
			if err != nil {
				return nil, err
			}
			m, err := parseMessage(p, name, p.name+"/msg/"+name, string(src))
			if err != nil {
				return nil, fmt.Errorf("%s: %w", f, err)
			}
			p.msgs = append(p.msgs, m)
			p.srcFiles[name] = string(src)
		}
		srvDir := filepath.Join(root, e.Name(), "srv")
		files, _ = filepath.Glob(filepath.Join(srvDir, "*.srv"))
		sort.Strings(files)
		for _, f := range files {
			name := strings.TrimSuffix(filepath.Base(f), ".srv")
			src, err := os.ReadFile(f)
			if err != nil {
				return nil, err
			}
			reqSrc, resSrc, ok := splitService(string(src))
			if !ok {
				return nil, fmt.Errorf("%s: missing --- separator", f)
			}
			req, err := parseMessage(p, name+"_Request", p.name+"/srv/"+name+"_Request", reqSrc)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", f, err)
			}
			res, err := parseMessage(p, name+"_Response", p.name+"/srv/"+name+"_Response", resSrc)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", f, err)
			}
			p.srvs = append(p.srvs, &service{name: name, ros: p.name + "/srv/" + name, req: req, res: res})
			p.srcFiles[name] = string(src)
		}
		if len(p.msgs)+len(p.srvs) > 0 {
			pkgs = append(pkgs, p)
		}
	}
	return pkgs, nil
}

// isConstName reports whether s is a ROS constant name (UPPER_CASE).
func isConstName(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if !((c >= 'A' && c <= 'Z') || c == '_' || (c >= '0' && c <= '9')) {
			return false
		}
	}
	return true
}

// splitService splits a .srv file at its "---" line.
func splitService(src string) (req, res string, ok bool) {
	lines := strings.Split(src, "\n")
	for i, l := range lines {
		if strings.TrimSpace(l) == "---" {
			return strings.Join(lines[:i], "\n"), strings.Join(lines[i+1:], "\n"), true
		}
	}
	return "", "", false
}

func parseMessage(p *pkg, goName, rosName, src string) (*message, error) {
	m := &message{pkg: p, name: goName, ros: rosName}
	for lineNo, line := range strings.Split(src, "\n") {
		if i := strings.IndexByte(line, '#'); i >= 0 {
			// '#' inside a string default ("#foo") is rare; ignore that case.
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		toks := strings.Fields(line)
		if len(toks) < 2 {
			return nil, fmt.Errorf("line %d: expected 'type name'", lineNo+1)
		}
		ft, err := parseType(p, toks[0])
		if err != nil {
			return nil, fmt.Errorf("line %d: %w", lineNo+1, err)
		}
		rest := strings.TrimSpace(line[len(toks[0]):])
		if eq := strings.IndexByte(rest, '='); eq >= 0 && isConstName(strings.TrimSpace(rest[:eq])) {
			// constant: NAME=value
			m.consts = append(m.consts, field{name: strings.TrimSpace(rest[:eq]), typ: ft, constant: true, value: strings.TrimSpace(rest[eq+1:])})
			continue
		}
		f := field{name: toks[1], typ: ft}
		if len(toks) > 2 {
			f.def = strings.TrimSpace(rest[len(toks[1]):])
		}
		m.fields = append(m.fields, f)
	}
	return m, nil
}

func parseType(p *pkg, s string) (fieldType, error) {
	var ft fieldType
	// array suffix
	if i := strings.IndexByte(s, '['); i >= 0 {
		if !strings.HasSuffix(s, "]") {
			return ft, fmt.Errorf("bad array type %q", s)
		}
		spec := s[i+1 : len(s)-1]
		s = s[:i]
		switch {
		case spec == "":
			ft.isSeq = true
		case strings.HasPrefix(spec, "<="):
			ft.isSeq = true
			fmt.Sscanf(spec[2:], "%d", &ft.size)
		default:
			ft.isArray = true
			if _, err := fmt.Sscanf(spec, "%d", &ft.size); err != nil || ft.size <= 0 {
				return ft, fmt.Errorf("bad array size %q", spec)
			}
		}
	}
	// bounded string
	if strings.HasPrefix(s, "string<=") || strings.HasPrefix(s, "wstring<=") {
		i := strings.Index(s, "<=")
		fmt.Sscanf(s[i+2:], "%d", &ft.strMax)
		s = s[:i]
	}
	if g, ok := primitives[s]; ok {
		ft.base = s
		ft.name = g
		return ft, nil
	}
	if strings.Contains(s, "/") {
		parts := strings.Split(s, "/")
		if len(parts) != 2 {
			return ft, fmt.Errorf("bad type %q", s)
		}
		ft.base = s
		ft.pkg = parts[0]
		ft.name = parts[1]
		if ft.pkg != p.name {
			p.deps[ft.pkg] = true
		}
		return ft, nil
	}
	// same package reference
	ft.base = p.name + "/" + s
	ft.pkg = p.name
	ft.name = s
	return ft, nil
}

// --- codegen ---------------------------------------------------------------

func goField(n string) string {
	parts := strings.Split(n, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func (ft fieldType) goType(cur string) string {
	elem := ft.name
	if ft.pkg != "" && ft.pkg != cur {
		elem = ft.pkg + "." + ft.name
	}
	switch {
	case ft.isArray:
		return fmt.Sprintf("[%d]%s", ft.size, elem)
	case ft.isSeq:
		return "[]" + elem
	}
	return elem
}

func (ft fieldType) isPrimitive() bool { return ft.pkg == "" }

// cdr method name for a primitive scalar.
func (ft fieldType) cdrName() string {
	switch ft.base {
	case "bool":
		return "Bool"
	case "byte", "char", "uint8":
		return "Uint8"
	case "int8":
		return "Int8"
	case "int16":
		return "Int16"
	case "uint16":
		return "Uint16"
	case "int32":
		return "Int32"
	case "uint32":
		return "Uint32"
	case "int64":
		return "Int64"
	case "uint64":
		return "Uint64"
	case "float32":
		return "Float32"
	case "float64":
		return "Float64"
	case "string":
		return "String"
	case "wstring":
		return "WString"
	}
	return ""
}

func snake(name string) string {
	var b strings.Builder
	for i, r := range name {
		if r >= 'A' && r <= 'Z' {
			if i > 0 && (name[i-1] < 'A' || name[i-1] > 'Z') {
				b.WriteByte('_')
			} else if i > 0 && i+1 < len(name) && name[i+1] >= 'a' && name[i+1] <= 'z' && name[i-1] != '_' {
				b.WriteByte('_')
			}
			b.WriteRune(r + 32)
		} else {
			b.WriteRune(r)
		}
	}
	return strings.ReplaceAll(b.String(), "__", "_")
}

func (p *pkg) generate(out, module string) error {
	dir := filepath.Join(out, p.name)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	// Remove stale generated files.
	old, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, f := range old {
		data, _ := os.ReadFile(f)
		if bytes.HasPrefix(data, []byte("// Code generated by msggen")) {
			os.Remove(f)
		}
	}
	for _, m := range p.msgs {
		src, err := p.render(module, []*message{m}, nil, p.srcFiles[m.name])
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, snake(m.name)+".go"), src, 0o644); err != nil {
			return err
		}
	}
	for _, s := range p.srvs {
		src, err := p.render(module, []*message{s.req, s.res}, s, p.srcFiles[s.name])
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, snake(s.name)+"_srv.go"), src, 0o644); err != nil {
			return err
		}
	}
	doc := fmt.Sprintf("// Code generated by msggen. DO NOT EDIT.\n\n// Package %s contains Go types for the ROS 2 %q interface package.\npackage %s\n", p.name, p.name, p.name)
	return os.WriteFile(filepath.Join(dir, "doc.go"), []byte(doc), 0o644)
}

func (p *pkg) render(module string, msgs []*message, srv *service, src string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by msggen. DO NOT EDIT.\n\npackage %s\n\n", p.name)
	deps := map[string]bool{}
	for _, m := range msgs {
		for _, f := range m.fields {
			if f.typ.pkg != "" && f.typ.pkg != p.name {
				deps[f.typ.pkg] = true
			}
		}
	}
	fmt.Fprintf(&b, "import (\n\t\"bitbucket.org/goros/cdr\"\n\t\"bitbucket.org/goros/msg\"\n")
	var depList []string
	for d := range deps {
		depList = append(depList, d)
	}
	sort.Strings(depList)
	for _, d := range depList {
		fmt.Fprintf(&b, "\t%q\n", module+"/"+d)
	}
	fmt.Fprintf(&b, ")\n\n")

	// Keep the original definition as documentation.
	if src != "" {
		fmt.Fprintf(&b, "// Interface definition:\n//\n")
		for _, line := range strings.Split(strings.TrimRight(src, "\n"), "\n") {
			fmt.Fprintf(&b, "//\t%s\n", line)
		}
		fmt.Fprintf(&b, "\n")
	}

	if srv != nil {
		fmt.Fprintf(&b, "// %sServiceName is the ROS 2 service type name.\nconst %sServiceName = %q\n\n", srv.name, srv.name, srv.ros)
	}

	for _, m := range msgs {
		m.renderType(&b)
	}
	fmt.Fprintf(&b, "func init() {\n")
	if srv != nil {
		fmt.Fprintf(&b, "\tmsg.RegisterService(%q, func() msg.Message { return new(%s) }, func() msg.Message { return new(%s) })\n", srv.ros, srv.req.name, srv.res.name)
	}
	for _, m := range msgs {
		fmt.Fprintf(&b, "\tmsg.Register(%q, func() msg.Message { return new(%s) })\n", m.ros, m.name)
	}
	fmt.Fprintf(&b, "}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format: %w\n%s", err, b.String())
	}
	return formatted, nil
}

func (m *message) renderType(b *bytes.Buffer) {
	cur := m.pkg.name
	// constants
	if len(m.consts) > 0 {
		fmt.Fprintf(b, "const (\n")
		for _, c := range m.consts {
			fmt.Fprintf(b, "\t%s_%s %s = %s\n", m.name, c.name, c.typ.goType(cur), goLiteral(c.typ, c.value))
		}
		fmt.Fprintf(b, ")\n\n")
	}
	// struct
	fmt.Fprintf(b, "// %s is the ROS 2 message %q.\ntype %s struct {\n", m.name, m.ros, m.name)
	for _, f := range m.fields {
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", goField(f.name), f.typ.goType(cur), f.name)
	}
	fmt.Fprintf(b, "}\n\n")

	// constructor + defaults
	fmt.Fprintf(b, "// New%s allocates a message with field defaults applied.\nfunc New%s() *%s {\n\tm := &%s{}\n\tm.SetDefaults()\n\treturn m\n}\n\n", m.name, m.name, m.name, m.name)
	fmt.Fprintf(b, "// SetDefaults resets fields that declare a default value.\nfunc (m *%s) SetDefaults() {\n", m.name)
	for _, f := range m.fields {
		g := goField(f.name)
		switch {
		case f.def != "":
			fmt.Fprintf(b, "\tm.%s = %s\n", g, goDefault(f.typ, f.def, cur))
		case !f.typ.isPrimitive() && !f.typ.isSeq && !f.typ.isArray:
			fmt.Fprintf(b, "\tm.%s.SetDefaults()\n", g)
		case !f.typ.isPrimitive() && f.typ.isArray:
			fmt.Fprintf(b, "\tfor i := range m.%s {\n\t\tm.%s[i].SetDefaults()\n\t}\n", g, g)
		}
	}
	fmt.Fprintf(b, "}\n\n")

	fmt.Fprintf(b, "// TypeName implements msg.Message.\nfunc (m *%s) TypeName() string { return %q }\n\n", m.name, m.ros)

	// marshal
	fmt.Fprintf(b, "// MarshalCDR implements msg.Message.\nfunc (m *%s) MarshalCDR(e *cdr.Encoder) {\n", m.name)
	for _, f := range m.fields {
		g := "m." + goField(f.name)
		t := f.typ
		switch {
		case t.isPrimitive() && !t.isSeq && !t.isArray:
			fmt.Fprintf(b, "\te.%s(%s)\n", t.cdrName(), g)
		case t.isPrimitive() && t.isSeq:
			if t.cdrName() == "Uint8" {
				fmt.Fprintf(b, "\te.BytesSeq(%s)\n", g)
			} else {
				fmt.Fprintf(b, "\te.%sSeq(%s)\n", t.cdrName(), g)
			}
		case t.isPrimitive() && t.isArray:
			if t.cdrName() == "Uint8" {
				fmt.Fprintf(b, "\te.RawBytes(%s[:])\n", g)
			} else {
				fmt.Fprintf(b, "\tfor i := range %s {\n\t\te.%s(%s[i])\n\t}\n", g, t.cdrName(), g)
			}
		case t.isSeq:
			fmt.Fprintf(b, "\te.SeqLen(len(%s))\n\tfor i := range %s {\n\t\t%s[i].MarshalCDR(e)\n\t}\n", g, g, g)
		case t.isArray:
			fmt.Fprintf(b, "\tfor i := range %s {\n\t\t%s[i].MarshalCDR(e)\n\t}\n", g, g)
		default:
			fmt.Fprintf(b, "\t%s.MarshalCDR(e)\n", g)
		}
	}
	if len(m.fields) == 0 {
		// Empty messages serialize as a single padding byte (rosidl behaviour).
		fmt.Fprintf(b, "\te.Uint8(0)\n")
	}
	fmt.Fprintf(b, "}\n\n")

	// unmarshal
	fmt.Fprintf(b, "// UnmarshalCDR implements msg.Message.\nfunc (m *%s) UnmarshalCDR(d *cdr.Decoder) {\n", m.name)
	for _, f := range m.fields {
		g := "m." + goField(f.name)
		t := f.typ
		switch {
		case t.isPrimitive() && !t.isSeq && !t.isArray:
			fmt.Fprintf(b, "\t%s = d.%s()\n", g, t.cdrName())
		case t.isPrimitive() && t.isSeq:
			if t.cdrName() == "Uint8" {
				fmt.Fprintf(b, "\t%s = d.BytesSeq()\n", g)
			} else {
				fmt.Fprintf(b, "\t%s = d.%sSeq()\n", g, t.cdrName())
			}
		case t.isPrimitive() && t.isArray:
			if t.cdrName() == "Uint8" {
				fmt.Fprintf(b, "\td.RawBytes(%s[:])\n", g)
			} else {
				fmt.Fprintf(b, "\tfor i := range %s {\n\t\t%s[i] = d.%s()\n\t}\n", g, g, t.cdrName())
			}
		case t.isSeq:
			fmt.Fprintf(b, "\tif n := d.SeqLen(1); d.Err() == nil {\n\t\t%s = make(%s, n)\n\t\tfor i := range %s {\n\t\t\t%s[i].UnmarshalCDR(d)\n\t\t}\n\t}\n", g, t.goType(cur), g, g)
		case t.isArray:
			fmt.Fprintf(b, "\tfor i := range %s {\n\t\t%s[i].UnmarshalCDR(d)\n\t}\n", g, g)
		default:
			fmt.Fprintf(b, "\t%s.UnmarshalCDR(d)\n", g)
		}
	}
	if len(m.fields) == 0 {
		fmt.Fprintf(b, "\t_ = d.Uint8()\n")
	}
	fmt.Fprintf(b, "}\n\n")
}

func goLiteral(t fieldType, v string) string {
	switch t.base {
	case "string", "wstring":
		if strings.HasPrefix(v, "'") && strings.HasSuffix(v, "'") {
			v = v[1 : len(v)-1]
			return fmt.Sprintf("%q", v)
		}
		if strings.HasPrefix(v, "\"") {
			return v
		}
		return fmt.Sprintf("%q", v)
	case "bool":
		return strings.ToLower(v)
	}
	return v
}

func goDefault(t fieldType, v, cur string) string {
	if t.isSeq || t.isArray {
		v = strings.TrimSpace(v)
		v = strings.TrimPrefix(v, "[")
		v = strings.TrimSuffix(v, "]")
		var elems []string
		for _, e := range strings.Split(v, ",") {
			e = strings.TrimSpace(e)
			if e != "" {
				elems = append(elems, goLiteral(t, e))
			}
		}
		return t.goType(cur) + "{" + strings.Join(elems, ", ") + "}"
	}
	return goLiteral(t, v)
}
